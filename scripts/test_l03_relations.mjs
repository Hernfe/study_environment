import assert from 'node:assert/strict';
import {evaluateRelation as r,checkQuantity as check} from '../src/js/numeric.js';
import c from '../src/content/nbe-e4120/L03.js';
const near=(a,b)=>assert(Math.abs(a-b)<=1e-12*Math.max(Math.abs(a),Math.abs(b),1e-200),`${a} != ${b}`);
const a=2e-6, rm=r('cableMembrane',{specific:2,radius:a}),ri=r('cableAxial',{rho:2,radius:a}),cm=r('cableCapacitance',{specific:.01,radius:a});
near(r('cableLength',{rm,ri}),.001);near(rm*cm,.02);
near(r('cableLength',{rm,ri,ro:3*ri}),.0005);
near(r('cableAxial',{rho:2,radius:2*a}),ri/4);
near(r('cableMembrane',{specific:2,radius:2*a}),rm/2);
near(r('cableCapacitance',{specific:.01,radius:2*a}),2*cm);
for(const x of [.001,-.001])near(r('cableDecay',{v:.01,x,lambda:.001}),.01/Math.E);
near(r('cableInverse',{x:.0006,fraction:1/3}),.0006/Math.log(3));
near(r('cableEvolution',{lambda:.001,curvature:0,v:.01,tau:.02}),-.5);
near(r('cableEvolution',{lambda:.001,curvature:1e4,v:.01,tau:.02}),0);
near(r('cableEvolution',{lambda:.001,curvature:0,v:.01,tau:.02,rm:1e5,injection:1e-7}),0);
for(const [text,answer] of [['1 mm',{value:.001,unit:'m',tolerance:1e-8}],['200 ohm*cm',{value:2,unit:'ohm*m',tolerance:.001}],['20 kΩ·cm²',{value:2,unit:'ohm*m2',tolerance:.001}],['1 ohm/cm',{value:100,unit:'ohm/m',tolerance:.01}],['1 mV/mm',{value:1,unit:'V/m',tolerance:.001}]])assert(check(text,answer).correct,text);
assert(check('1 F',{value:1,unit:'F/m',tolerance:.01}).error);
for(const q of c.lectureQuiz)for(const s of q.stages||[])for(const f of s.fields||[])if(f.answer.value!==0)assert(!check('0',f.answer).correct,`${q.id}: zero accepted`);
console.log('L03 relations: geometry, radius powers, tau cancellation, external resistance, symmetric decay, inverse inference, source-free and forced evolution, equivalent units and zero rejection PASS.');
